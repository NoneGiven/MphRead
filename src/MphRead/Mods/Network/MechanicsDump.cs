using System;
using System.Text;
using MphRead.Entities;

namespace MphRead.Mods.Network
{
    /// <summary>
    /// Prints the game's own tables as markdown: `MphRead -mechanics`.
    ///
    /// Written as a dump of the live data rather than as a hand-kept document,
    /// because a hand-kept one is wrong the moment anybody edits a table and
    /// nobody notices. Everything here is read out of Weapons.cs, Metadata and
    /// the damage code at runtime, so it cannot drift from what the game does.
    ///
    /// The rules that are expressed as code rather than as a table -- the
    /// Imperialist's zoom penalty, double damage, the difficulty multiplier --
    /// are listed with the file and line they live in, so the claim can be
    /// checked rather than believed.
    /// </summary>
    public static class MechanicsDump
    {
        public static void Run()
        {
            var text = new StringBuilder();
            text.AppendLine("# Metroid Prime Hunters — multiplayer mechanics");
            text.AppendLine();
            text.AppendLine("Generated by `MphRead -mechanics` from the game's own tables.");
            text.AppendLine();
            Weapons(text);
            DamageRules(text);
            Hunters(text);
            Movement(text);
            States(text);
            SpawnRules(text);
            Modes(text);
            World(text);
            Items(text);
            Bots(text);
            Networking(text);
            Console.Write(text.ToString());
        }

        private static void Weapons(StringBuilder text)
        {
            text.AppendLine("## Weapons (multiplayer table)");
            text.AppendLine();
            text.AppendLine("Damage is per shot before any multiplier. \"Charged\" is a full charge; "
                + "\"min\" is the smallest charge that counts as charged.");
            text.AppendLine();
            text.AppendLine("| Beam | dmg | min-chg | charged | headshot | hs charged | splash | "
                + "ammo | cost | cooldown | afflictions | notes |");
            text.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|");
            // The table holds each weapon twice: entries 0-8 are the plain
            // versions and 9-17 the affinity ones, which is how
            // `Weapons.Current[(int)beam + 9]` picks the stronger variant for
            // the hunter the weapon belongs to.
            for (int i = 0; i < MphRead.Weapons.WeaponsMP.Count && i < 18; i++)
            {
                WeaponInfo weapon = MphRead.Weapons.WeaponsMP[i];
                if (weapon.Beam < BeamType.PowerBeam || weapon.Beam > BeamType.OmegaCannon)
                {
                    continue;
                }
                if (i == 9)
                {
                    text.AppendLine();
                    text.AppendLine("Affinity versions -- what a hunter gets when it carries its own "
                        + "weapon. Note the extra damage and the afflictions the plain versions "
                        + "do not have:");
                    text.AppendLine();
                    text.AppendLine("| Beam | dmg | min-chg | charged | headshot | hs charged | splash | "
                        + "ammo | cost | cooldown | afflictions | notes |");
                    text.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|");
                }
                var notes = new StringBuilder();
                void Note(string value)
                {
                    if (notes.Length > 0)
                    {
                        notes.Append(", ");
                    }
                    notes.Append(value);
                }
                if (weapon.Flags.TestFlag(WeaponFlags.CanZoom)) Note("can zoom");
                if (weapon.Flags.TestFlag(WeaponFlags.Continuous)) Note("continuous");
                if (weapon.Flags.TestFlag(WeaponFlags.RepeatFire)) Note("repeat fire");
                if (weapon.Flags.TestFlag(WeaponFlags.CanCharge)) Note("chargeable");
                if (weapon.Flags.TestFlag(WeaponFlags.RicochetUncharged)
                    || weapon.Flags.TestFlag(WeaponFlags.RicochetCharged)) Note("ricochets");
                if (weapon.Flags.TestFlag(WeaponFlags.AoeUncharged)
                    || weapon.Flags.TestFlag(WeaponFlags.AoeCharged)) Note("area of effect");
                if (weapon.Flags.TestFlag(WeaponFlags.SelfDamageUncharged)
                    || weapon.Flags.TestFlag(WeaponFlags.SelfDamageCharged)) Note("can hurt the shooter");
                // Index 0 is the uncharged shot and index 1 the charged one.
                // Saying which is not a detail: every affliction in the game
                // sits on the charged entry, so a table that listed "Freeze"
                // without saying when read as "this weapon freezes people",
                // and a test that tapped the trigger could never reach it.
                var afflictions = new StringBuilder();
                for (int j = 0; j < weapon.Afflictions.Count; j++)
                {
                    if (weapon.Afflictions[j] != Affliction.None)
                    {
                        afflictions.Append(afflictions.Length > 0 ? ", " : "");
                        afflictions.Append(j == 0 ? "" : "charged: ");
                        afflictions.Append(weapon.Afflictions[j]);
                    }
                }
                text.AppendLine($"| {weapon.Beam} | {weapon.UnchargedDamage} | {weapon.MinChargeDamage} "
                    + $"| {weapon.ChargedDamage} | {weapon.HeadshotDamage} | {weapon.ChargedHeadshotDamage} "
                    + $"| {weapon.SplashDamage}/{weapon.ChargedSplashDamage} "
                    + $"| {(weapon.AmmoType == 0 ? "UA" : "missile")} | {weapon.AmmoCost}/{weapon.ChargeCost} "
                    + $"| {weapon.ShotCooldown} | {(afflictions.Length > 0 ? afflictions.ToString() : "-")} "
                    + $"| {(notes.Length > 0 ? notes.ToString() : "-")} |");
            }
            text.AppendLine();
            text.AppendLine();
            text.AppendLine("Affinity weapon per hunter (the one whose enhanced version it uses):");
            text.AppendLine();
            for (int i = 0; i < 7; i++)
            {
                text.AppendLine($"- {(Hunter)i}: {MphRead.Weapons.GetAffinityBeam((Hunter)i)}");
            }
            text.AppendLine();
        }

        private static void DamageRules(StringBuilder text)
        {
            text.AppendLine("## Damage multipliers, in the order the code applies them");
            text.AppendLine();
            text.AppendLine("| Rule | Effect | Where |");
            text.AppendLine("|---|---|---|");
            text.AppendLine("| Beam effectiveness vs the target | x0 / x0.5 / x1 / x2 | "
                + "`PlayerEntity.TakeDamage`, from `BeamEffectiveness[beam]`. Players are set to "
                + "Normal for every beam in `Spawn()`; **a player that never spawned has x0 for "
                + "everything and cannot be hurt at all** |");
            text.AppendLine("| Double damage pickup | x2, and *not* applied to Shock Coil | "
                + "`BeamProjectileEntity` |");
            text.AppendLine("| Prime Hunter | x1.5 | `BeamProjectileEntity` |");
            text.AppendLine("| **Imperialist without zoom** | **/2** | "
                + "`BeamProjectileEntity`: `if (weapon.Beam == Imperialist && !equip.Zoomed) damage /= 2` |");
            text.AppendLine("| Quadruple Damage cheat | x4 | `BeamProjectileEntity`, from settings.json. "
                + "Disabled automatically while connected to a server |");
            text.AppendLine("| Match damage level | "
                + $"x{Metadata.DamageLevels[0]} low / x{Metadata.DamageLevels[1]} medium / "
                + $"x{Metadata.DamageLevels[2]} high | `PlayerEntity.TakeDamage` |");
            text.AppendLine("| Headshot | uses the weapon's headshot damage instead | "
                + "`BeamProjectileEntity` |");
            text.AppendLine("| Friendly fire off, same team | x0 | `PlayerEntity.TakeDamage` |");
            text.AppendLine("| Weavel halfturret alive | damage is split between body and turret | "
                + "`PlayerEntity.TakeDamage` |");
            text.AppendLine("| Affinity weapon | the hunter uses entry `beam + 9`, which is a "
                + "different set of numbers entirely -- more damage and, for several weapons, an "
                + "affliction the plain version does not inflict | `PlayerEntity.TryEquipWeapon` |");
            text.AppendLine();
            text.AppendLine("Invulnerability windows: a hit sets a damage-invulnerability timer "
                + "(per hunter, `Values.DamageInvuln`), and spawning sets a spawn-invulnerability "
                + "timer. Both reject further damage until they run out.");
            text.AppendLine();
        }

        private static void Hunters(StringBuilder text)
        {
            text.AppendLine("## Hunters");
            text.AppendLine();
            text.AppendLine("| Hunter | energy tank | MP max health | MP ammo cap | alt form | "
                + "bombs | boost | alt attack |");
            text.AppendLine("|---|---|---|---|---|---|---|---|");
            for (int i = 0; i < 7; i++)
            {
                var hunter = (Hunter)i;
                PlayerValues values = Metadata.PlayerValues[i];
                bool bombs = hunter == Hunter.Samus || hunter == Hunter.Kanden || hunter == Hunter.Sylux;
                bool boost = hunter == Hunter.Samus;
                string alt = hunter switch
                {
                    Hunter.Samus => "Morph Ball",
                    Hunter.Kanden => "Stinglarva",
                    Hunter.Trace => "Triskelion",
                    Hunter.Sylux => "Lockjaw",
                    Hunter.Noxus => "Vhoscythe",
                    Hunter.Spire => "Dialanche",
                    Hunter.Weavel => "Halfturret",
                    _ => "-"
                };
                string altAttack = hunter switch
                {
                    Hunter.Trace => "cloak and lunge",
                    Hunter.Noxus => "spin attack",
                    Hunter.Spire => "slam",
                    Hunter.Weavel => "leaves a turret that shoots on its own",
                    _ => "bombs"
                };
                text.AppendLine($"| {hunter} | {values.EnergyTank} | {2 * values.EnergyTank - 1} "
                    + $"| {values.MpAmmoCap} | {alt} | {(bombs ? "yes" : "no")} "
                    + $"| {(boost ? "yes" : "no")} | {altAttack} |");
            }
            text.AppendLine();
            text.AppendLine("Health on spawn is `EnergyTank - 1`; the maximum in multiplayer is "
                + "`2 * EnergyTank - 1`, so a full pickup run doubles a hunter's effective health.");
            text.AppendLine();
        }

        private static void Movement(StringBuilder text)
        {
            text.AppendLine("## Movement, per hunter");
            text.AppendLine();
            text.AppendLine("Speeds are units per frame as the engine stores them (20.12 fixed "
                + "point converted to float on load).");
            text.AppendLine();
            text.AppendLine("| Hunter | walk cap | strafe cap | jump | biped gravity | alt gravity (air/ground) "
                + "| boost cap | boost charge (min-max) | alt radius |");
            text.AppendLine("|---|---|---|---|---|---|---|---|---|");
            for (int i = 0; i < 7; i++)
            {
                PlayerValues v = Metadata.PlayerValues[i];
                text.AppendLine($"| {(Hunter)i} | {Fixed.ToFloat(v.WalkSpeedCap):0.###} "
                    + $"| {Fixed.ToFloat(v.StrafeSpeedCap):0.###} | {Fixed.ToFloat(v.JumpSpeed):0.###} "
                    + $"| {Fixed.ToFloat(v.BipedGravity):0.####} "
                    + $"| {Fixed.ToFloat(v.AltAirGravity):0.####}/{Fixed.ToFloat(v.AltGroundGravity):0.####} "
                    + $"| {Fixed.ToFloat(v.BoostSpeedCap):0.###} | {v.BoostChargeMin}-{v.BoostChargeMax} "
                    + $"| {Fixed.ToFloat(v.AltColRadius):0.###} |");
            }
            text.AppendLine();
            text.AppendLine("- Morphing plays an animation and the form only changes when it ends "
                + "(`EnterAltForm` sets Morphing; `ProcessPlayer` applies `UpdateForm` on "
                + "`AnimFlags.Ended`). Unmorphing applies the change immediately.");
            text.AppendLine("- Alt form swaps the collision volume (`PlayerVolumes[hunter, 2]`), and "
                + "the position is shifted by the difference between the two volume centres.");
            text.AppendLine("- Boost is a charge-then-release: hold to build from `BoostChargeMin` to "
                + "`BoostChargeMax`, release to convert it into speed between `BoostSpeedMin` and "
                + "`BoostSpeedMax`.");
            text.AppendLine();
        }

