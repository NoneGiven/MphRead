        private static void Bots(StringBuilder text)
        {
            text.AppendLine("## Bots");
            text.AppendLine();
            text.AppendLine("A bot is an ordinary player whose `Controls` are written by "
                + "`PlayerAi.ProcessInput` instead of by a keyboard. That is the whole of the "
                + "difference, and it is why a networked player can reuse the same surface: "
                + "relayed input is simply a third writer of the same buttons.");
            text.AppendLine();
            text.AppendLine("| Piece | What it does |");
            text.AppendLine("|---|---|");
            text.AppendLine("| `PlayerEntity.IsBot` | marks the slot as AI-driven. "
                + "`Scene.AddPlayer` sets it on every player after the first, which is right for a "
                + "local match and wrong for a networked one -- the AI would overwrite relayed "
                + "input, so a networked session clears it on every slot |");
            text.AppendLine("| `BotLevel` (0-2) | difficulty; clamped and used to index reaction "
                + "and accuracy tables |");
            text.AppendLine("| `AiPersonality` | per-hunter behaviour trees loaded from the ROM's "
                + "own data, one set per hunter and encounter. `AiPersonalityData1` nodes hold "
                + "conditions and the function ids to run |");
            text.AppendLine("| `AiData.Process()` | run once per frame per bot from "
                + "`Scene.UpdateScene`, but only while the bot is alive |");
            text.AppendLine("| `UpdateExecutionPath` / `Execute` | walks the tree and dispatches "
                + "`Func24Id` to the behaviour functions -- move, aim, fire, morph, use the alt "
                + "attack, pick a weapon |");
            text.AppendLine("| Weapon choice | prefers the hunter's affinity weapon "
                + "(`Weapons.AffinityWeapons[hunter]`) and zooms when it holds a weapon that can |");
            text.AppendLine("| `AiFlags3` | the spawn/despawn handshake: one bit asks for the spawn "
                + "effect and sound, another marks the bot as despawned |");
            text.AppendLine();
            text.AppendLine("For testing, `NetTestScript` replaces the AI entirely: it writes the "
                + "same `Controls`, but to a fixed script rather than a behaviour tree, so two "
                + "machines can be asked to do the same thing at the same moment and compared.");
            text.AppendLine();
        }

        private static void Networking(StringBuilder text)
        {
            text.AppendLine("## How multiplayer works here");
            text.AppendLine();
            text.AppendLine("This is not the DS Wi-Fi protocol and cannot talk to real hardware or "
                + "an emulator. It connects MphRead instances to each other.");
            text.AppendLine();
            text.AppendLine("| Piece | Rule |");
            text.AppendLine("|---|---|");
            text.AppendLine("| Server | a relay with no game files: it assigns slots, keeps the "
                + "match clock and the map rotation, and forwards packets. It never simulates |");
            text.AppendLine("| Authority | the first client to connect. It resolves damage, deaths "
                + "and scores for everybody |");
            text.AppendLine("| Position | owned by the player it belongs to. Each client publishes "
                + "its own position in every intent and everyone else follows it, including the "
                + "authority. Two simulations of one player fighting over a position is what "
                + "produced rubber-banding |");
            text.AppendLine("| Input | relayed to every client, not only the authority. Input is "
                + "what makes a player fire, morph, lay a bomb or swing an alt attack; clients that "
                + "received only positions drew opponents gliding in silence |");
            text.AppendLine("| One-frame presses | carried as an 8-frame history of rising edges, "
                + "because a press exists in exactly one packet and UDP loses packets. Edges are "
                + "taken *only* from that history: deriving them from the button level as well "
                + "applied each press twice, which for a toggle means never |");
            text.AppendLine("| Snapshot | the authority's view of every player: health, score, "
                + "form, weapon, zoom, and a damage record. Sent every frame |");
            text.AppendLine("| Damage | resolved only by the authority; every other client throws "
                + "away locally-resolved hits. The authority stamps each hit with a counter, and "
                + "victims replay the *difference* in that counter, so several hits between two "
                + "snapshots are all accounted for |");
            text.AppendLine("| Score | carried in the snapshot. Counting locally worked only for "
                + "whoever had been present since the first kill |");
            text.AppendLine("| Remote smoothing | remote players ease toward their reported "
                + "position (35% of the gap per frame, 60% when it is wide) and only jump past 15 "
                + "units, so a lost burst glides instead of popping |");
            text.AppendLine("| Lag compensation | the authority rewinds every other player to "
                + "the snapshot frame the shooter had acknowledged, spawns the shot into that "
                + "world, and then walks it forward to the present one frame at a time. Bounded "
                + "at 24 frames (400 ms) of rewind and 64 frames of history. The authority's own "
                + "shots are rewound by zero: it already aims at the puppets it resolves "
                + "against |");
            text.AppendLine("| Slots | `PlayerEntity.SlotCapacity` (8). Every slot-indexed array is "
                + "sized from it |");
            text.AppendLine("| Map rotation | the server owns it; clients poll the match state and "
                + "load the new room, rebuilding every player slot and resetting the scores |");
            text.AppendLine("| Chat | T opens a line, the server stamps it with the sender's real "
                + "slot and name and relays it to everybody else, and the sender echoes its own. "
                + "Rate limited at the relay: three back to back, then one every two seconds. "
                + "Additive on the wire, so an older server simply drops it |");
            text.AppendLine();
        }

