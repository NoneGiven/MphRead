        private static void SpawnRules(StringBuilder text)
        {
            text.AppendLine("## Spawning and respawning");
            text.AppendLine();
            text.AppendLine("`PlayerProcess.GetRespawnPoint` picks a point by these rules, in order:");
            text.AppendLine();
            text.AppendLine("1. Consider at most 25 spawn points. Skip any that is inactive, still "
                + "on cooldown, or (on the very first frame) flagged by availability.");
            text.AppendLine("2. In Capture, skip points belonging to the other team.");
            text.AppendLine("3. A point is *valid* only if every living player is at least 10 units "
                + "away. Among the valid ones, the choice rotates with the frame counter.");
            text.AppendLine("4. If none is valid, take the one furthest from any living player.");
            text.AppendLine("5. If even that is unavailable -- every point on cooldown, which happens "
                + "with more players than the map was drawn for -- take any active point. Without "
                + "this last step the player simply does not spawn and waits at the origin.");
            text.AppendLine();
            text.AppendLine("The chosen point goes on a cooldown of 2 frames doubled, so a crowd "
                + "cannot all land on the same one.");
            text.AppendLine();
            text.AppendLine("A dead player waits on `_respawnTimer`; it may spawn early by holding "
                + "fire. Health on spawn is `EnergyTank - 1`. **`Spawn()` is also what fills in "
                + "`BeamEffectiveness`** -- a player that reaches the map without it takes zero "
                + "damage from every beam in the game.");
            text.AppendLine();
        }

